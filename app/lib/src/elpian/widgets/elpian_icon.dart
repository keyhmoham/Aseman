class ElpianIcon {
  static Widget build(ElpianNode node, List<Widget> children) {
    final iconName = node.props['icon'] as String? ?? 'star';
    final size = node.style?.fontSize ?? node.props['size'] as double? ?? 24.0;
    final color = node.style?.color;

    // `svgPath`: an SVG path in a 24x24 viewBox, painted directly — there is
    // no SVG decoder to hand it to.
    final svgPath = node.props['svgPath'];
    if (svgPath is String && svgPath.isNotEmpty) {
      final label = node.props['semanticLabel'] as String?;
      Widget icon = SvgPathIcon(
        path: svgPath,
        size: size,
        color: color,
      );
      if (label != null && label.isNotEmpty) {
        icon = Semantics(label: label, image: true, child: icon);
      }
      if (node.style != null) icon = CSSProperties.applyStyle(icon, node.style);
      return icon;
    }

    Widget result = Icon(
      _getIcon(iconName),
      size: size,
      color: color,
    );

    if (node.style != null) {
      result = CSSProperties.applyStyle(result, node.style);
    }

    return result;
  }

  /// Whether [name] names a known icon (others render as a star).
  static bool hasIcon(String name) => iconData(name) != null;

  /// The icon [name] names (snake_case, kebab-case or camelCase; a
  /// `_rounded` / `_outlined` / `_sharp` style suffix is ignored), or null.
  static IconData? iconData(String name) {
    final snake = name
        .trim()
        .replaceAllMapped(RegExp('(?<=[a-z0-9])[A-Z]'), (m) => '_${m[0]}')
        .replaceAll(RegExp(r'[\s-]+'), '_')
        .toLowerCase();
    return _iconMap[snake] ??
        _iconMap[snake.replaceFirst(
          RegExp(r'_(rounded|outlined|outline|sharp|filled)$'),
          '',
        )];
  }

  static IconData _getIcon(String name) {
    return iconData(name) ?? Icons.star_rounded;
  }

