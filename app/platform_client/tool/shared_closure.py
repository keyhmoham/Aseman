#!/usr/bin/env python3
"""Lists the Aseman app's sources this client shares: the Elpian engine, the UI
kit and the host an Elpian frontend runs against, with everything they import.

    python3 tool/shared_closure.py           # rewrite tool/shared.txt
    python3 tool/shared_closure.py --check   # fail if it is out of date

The client keeps none of these files itself: tool/assemble.sh copies them from
../lib (app/lib) into lib/ when the client is assembled or built, so the
engine is the app's own, never a fork.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP_LIB = os.path.normpath(os.path.join(HERE, "..", "..", "lib"))
LIST = os.path.join(HERE, "shared.txt")

# What the client uses directly (paths under app/lib).
SEEDS = [
    "src/elpian/elpian.dart",
    "src/features/tools/ui_kit/kit.dart",
    "src/features/tools/elpian/host_values.dart",
    "src/features/tools/elpian_app/elpian_app_host.dart",
    "src/features/tools/presentation/app_frontend_theme.dart",
    "src/core/theme/app_theme.dart",
    "src/core/theme/aseman_tokens.dart",
    "src/core/theme/theme_pack.dart",
    "src/shared/widgets/skeleton.dart",
]

STATEMENT = re.compile(r"^\s*(?:import|export|part)\b[^;]*;", re.M | re.S)
URI = re.compile(r"'([^']+\.dart)'")


def closure():
    seen, external, stack = set(), set(), [os.path.join(APP_LIB, s) for s in SEEDS]
    while stack:
        path = os.path.normpath(stack.pop())
        if path in seen:
            continue
        if not os.path.exists(path):
            sys.exit("missing: " + os.path.relpath(path, APP_LIB))
        seen.add(path)
        with open(path, encoding="utf-8") as f:
            source = f.read()
        for statement in STATEMENT.findall(source):
            for uri in URI.findall(statement):
                if uri.startswith("dart:"):
                    continue
                if uri.startswith("package:aseman/"):
                    stack.append(os.path.join(APP_LIB, uri[len("package:aseman/"):]))
                elif uri.startswith("package:"):
                    external.add(uri.split("/")[0][len("package:"):])
                else:
                    stack.append(os.path.join(os.path.dirname(path), uri))
    return sorted(os.path.relpath(p, APP_LIB) for p in seen), sorted(external)


def main():
    files, external = closure()
    text = "# Generated by tool/shared_closure.py: app/lib sources this client shares.\n" + "\n".join(files) + "\n"
    if "--check" in sys.argv:
        with open(LIST, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit("tool/shared.txt is out of date: run python3 tool/shared_closure.py")
        return
    with open(LIST, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"{len(files)} files; packages: {', '.join(external)}")


if __name__ == "__main__":
    main()
